import { ESLint } from "eslint";
import { describe, expect, it } from "vitest";

import { ignores } from "../src/eslint.js";

const cwd = new URL("..", import.meta.url).pathname;

// Virtual file linted from memory; the type-aware parser must be told it may not exist on disk.
const FIXTURE = "test/__virtual__/fixture.ts";

async function lint(code: string) {
  const eslint = new ESLint({
    cwd,
    overrideConfig: {
      languageOptions: {
        parserOptions: { projectService: { allowDefaultProject: [FIXTURE] } },
      },
    },
  });
  const [result] = await eslint.lintText(code, { filePath: FIXTURE });
  const messages = result?.messages ?? [];
  const fatal = messages.find((m) => m.fatal);
  if (fatal) throw new Error(fatal.message);
  return messages.map((m) => m.ruleId);
}

describe("@secondbrain/config/eslint", () => {
  it("accepts clean, strictly typed code", async () => {
    const rules = await lint(
      "export function add(a: number, b: number): number {\n  return a + b;\n}\n",
    );
    expect(rules).toEqual([]);
  });

  it("enforces strict equality", async () => {
    const rules = await lint("export const same = (a: number, b: number) => a == b;\n");
    expect(rules).toContain("eqeqeq");
  });

  it("reports unused variables but allows the underscore escape hatch", async () => {
    const rules = await lint(
      "export function f(_ignored: string) {\n  const unused = 1;\n  return 2;\n}\n",
    );
    expect(rules).toEqual(["@typescript-eslint/no-unused-vars"]);
  });

  it("runs type-aware rules (floating promises)", async () => {
    const rules = await lint(
      "async function work(): Promise<void> {}\nexport function run() {\n  work();\n}\n",
    );
    expect(rules).toContain("@typescript-eslint/no-floating-promises");
  });

  it("never lints generated api-types (CLAUDE.md: generated by ts-rs)", () => {
    expect(ignores).toContain("**/api-types/**");
  });
});
