import { readdirSync, readFileSync } from "node:fs";

import { describe, expect, expectTypeOf, it } from "vitest";

import type { ErrorBody, ErrorCode, Page, ValidationErrors } from "../src/index";

const generated = new URL("../src/generated/", import.meta.url);
const index = readFileSync(new URL("../src/index.ts", import.meta.url), "utf8");

describe("@secondbrain/api-types", () => {
  it("re-exports every generated type", () => {
    const files = readdirSync(generated).filter((f) => f.endsWith(".ts"));
    expect(files.length).toBeGreaterThan(0);
    for (const file of files) {
      expect(index).toContain(`./generated/${file.replace(/\.ts$/, "")}`);
    }
  });

  it("generated files carry the do-not-edit header", () => {
    for (const file of readdirSync(generated)) {
      const text = readFileSync(new URL(file, generated), "utf8");
      expect(text.startsWith("// This file was generated by [ts-rs]")).toBe(true);
    }
  });

  it("matches the server's error wire format", () => {
    const body: ErrorBody = {
      error: {
        code: "validation_failed",
        message: "validation failed",
        fields: [{ field: "title", code: "required", message: "must not be blank" }],
      },
    };
    expect(body.error.fields?.[0]?.code).toBe("required");
    expectTypeOf<ErrorCode>().toEqualTypeOf<
      | "not_found"
      | "unauthenticated"
      | "forbidden"
      | "validation_failed"
      | "conflict"
      | "consent_required"
      | "rate_limited"
      | "internal"
    >();
    expectTypeOf<ValidationErrors[number]["field"]>().toBeString();
  });

  it("models pages with a nullable cursor", () => {
    const last: Page<string> = { items: ["a"], next_cursor: null };
    expect(last.next_cursor).toBeNull();
    expectTypeOf<Page<number>["items"]>().toEqualTypeOf<number[]>();
  });
});
